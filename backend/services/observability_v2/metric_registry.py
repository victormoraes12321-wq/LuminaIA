class OperationalMetricRegistryV2:
    @staticmethod
    def get_definition(metric_id: str) -> OperationalMetricDefinitionV2 | None:
        return _OPERATIONAL_METRICS.get(metric_id)

    @staticmethod
    def list_metrics() -> tuple[OperationalMetricDefinitionV2, ...]:
        return tuple(_OPERATIONAL_METRICS.values())

    @staticmethod
    def is_allowlisted(metric_id: str) -> bool:
        return metric_id in _OPERATIONAL_METRICS
